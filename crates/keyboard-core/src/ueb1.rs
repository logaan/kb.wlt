#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct State {
    pub numeric: bool,
    pub capitals: Capitals,
    pub word_start: bool,
    pending: [u16; 3],
    len: usize,
}

impl Default for State {
    fn default() -> Self {
        Self {
            numeric: false,
            capitals: Capitals::None,
            word_start: true,
            pending: [0; 3],
            len: 0,
        }
    }
}

fn condition(expected: i8, actual: bool) -> bool {
    expected == 0 || actual == (expected > 0)
}

impl State {
    pub fn pending(&self) -> &[u16] {
        &self.pending[..self.len]
    }

    pub fn after_text(&mut self, text: &[u8]) {
        *self = Self::default();
        self.word_start = text
            .last()
            .is_none_or(|byte| matches!(byte, b' ' | b'\n' | b'\t' | b'-'));
    }

    pub fn accept(&mut self, cell: u16) -> Bounded<KeyStroke, 4> {
        let mut output = Bounded::default();
        if cell == 0x40 || cell == 0x80 || cell & 0x100 != 0 {
            if let Some(stroke) = crate::computer8(cell) {
                self.len = 0;
                if matches!(stroke.usage, 40 | 43 | 44) {
                    self.transition(Class::Space, Capitals::None);
                } else {
                    *self = Self::default();
                }
                let _ = output.push(stroke);
            }
            return output;
        }
        if cell == 0 || cell > 0x3f {
            return output;
        }
        self.pending[self.len] = cell;
        self.len += 1;
        loop {
            let mut longest: Option<&Rule> = None;
            let mut extend = false;
            for rule in RULES {
                if !condition(rule.numeric, self.numeric)
                    || !condition(rule.caps, self.capitals != Capitals::None)
                    || !condition(rule.word, self.word_start)
                {
                    continue;
                }
                let count = usize::from(rule.count);
                let common = count.min(self.len);
                if rule.cells[..common] != self.pending[..common] {
                    continue;
                }
                if count > self.len {
                    extend = true;
                } else if longest.is_none_or(|previous| rule.count > previous.count) {
                    longest = Some(rule);
                }
            }
            if extend {
                break;
            }
            let consumed = if let Some(rule) = longest {
                for byte in rule.text.bytes() {
                    if let Some(stroke) = KeyStroke::from_ascii(byte) {
                        let _ = output.push(stroke);
                    }
                }
                self.transition(rule.class, rule.sets);
                usize::from(rule.count)
            } else {
                1
            };
            self.pending.copy_within(consumed..self.len, 0);
            self.len -= consumed;
            if self.len == 0 {
                break;
            }
        }
        output
    }

    fn transition(&mut self, class: Class, sets: Capitals) {
        match class {
            Class::Letter => {
                self.numeric = false;
                self.word_start = false;
            }
            Class::CapitalLetter => {
                self.numeric = false;
                self.end_word_capitals();
                self.word_start = false;
            }
            Class::Digit => {
                self.numeric = true;
                self.end_word_capitals();
                self.word_start = false;
            }
            Class::NumericPunctuation => {
                self.end_word_capitals();
                self.word_start = false;
            }
            Class::Space | Class::Hyphen => {
                self.numeric = false;
                self.end_word_capitals();
                self.word_start = true;
            }
            Class::Opening => {
                self.numeric = false;
                self.end_word_capitals();
            }
            Class::Other | Class::Grade1Indicator => {
                self.numeric = false;
                self.end_word_capitals();
                self.word_start = false;
            }
            Class::CapsIndicator => {
                self.numeric = false;
                if sets != Capitals::Word || self.capitals != Capitals::Passage {
                    self.capitals = sets;
                }
            }
        }
    }

    fn end_word_capitals(&mut self) {
        if self.capitals == Capitals::Word {
            self.capitals = Capitals::None;
        }
    }
}

pub fn map_cell(cell: u16) -> u32 {
    if let Some(command) = crate::braille::one_shot(cell) {
        return command.packed();
    }
    State::default()
        .accept(cell)
        .as_slice()
        .first()
        .map_or(0, |stroke| stroke.packed())
}
