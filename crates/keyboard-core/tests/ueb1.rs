#[test]
fn pending_indicators_and_context_match_the_zmk_reference() {
    use kb_core::ueb1::Capitals;
    let cases: &[(&str, &[u16], &[u16], bool, Capitals, bool)] = &[
        (
            "single capital stays pending without a timer",
            &[32],
            &[32],
            false,
            Capitals::None,
            true,
        ),
        (
            "numeric prefix stays pending without setting numeric mode",
            &[60],
            &[60],
            false,
            Capitals::None,
            true,
        ),
        (
            "word capitals waits for possible passage extension",
            &[32, 32],
            &[32, 32],
            false,
            Capitals::None,
            true,
        ),
        (
            "symbol Grade 1 waits for word or terminator extension",
            &[48],
            &[48],
            false,
            Capitals::None,
            true,
        ),
        (
            "word Grade 1 waits for passage extension",
            &[48, 48],
            &[48, 48],
            false,
            Capitals::None,
            true,
        ),
        (
            "passage Grade 1 commits silently",
            &[48, 48, 48],
            &[],
            false,
            Capitals::None,
            false,
        ),
        (
            "orphan numeric prefix does not change caps word context",
            &[32, 32, 1, 60, 53],
            &[],
            false,
            Capitals::Word,
            false,
        ),
        (
            "dropped symbol prefix can start a new quotation prefix",
            &[8, 24, 38],
            &[],
            false,
            Capitals::None,
            true,
        ),
        (
            "Grade 1 commits before a new incomplete capital",
            &[48, 32],
            &[32],
            false,
            Capitals::None,
            false,
        ),
        (
            "uncontracted wordsigns remain literal letters",
            &[3, 256, 9, 256, 25],
            &[],
            false,
            Capitals::None,
            false,
        ),
    ];
    for (name, cells, pending, numeric, capitals, word_start) in cases {
        let mut state = State::default();
        for cell in *cells {
            state.accept(*cell);
        }
        assert_eq!(state.pending(), *pending, "pending: {name}");
        assert_eq!(
            (state.numeric, state.capitals, state.word_start),
            (*numeric, *capitals, *word_start),
            "context: {name}"
        );
    }
}
